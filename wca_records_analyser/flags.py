def flag_class(country_id):
    """Return the flag-icons CSS class for a WCA country name, or None if unrecognised."""
    iso_code = COUNTRY_ISO_CODES.get(country_id)
    if iso_code is None:
        return None
    return f"fi fi-{iso_code}"
